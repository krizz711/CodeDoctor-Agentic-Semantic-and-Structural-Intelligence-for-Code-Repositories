"""Build a Kaggle CPU-only kernel that runs ``scripts/bench_query_cpu.py``.

R2/M2 was pre-registered on this laptop, but with the desktop apps open it has
~1.4 GB of free RAM, which cannot host even the 160M encoder with headroom.  A
fixed Kaggle CPU machine is used instead (no GPU, so no GPU quota), and the
machine is recorded in the result.

    python scripts/bench_query_cpu.py --build-subset build/kernel_cpubench/subset
    python scripts/build_cpubench_kernel.py
    kaggle kernels push -p build/kernel_cpubench
    kaggle kernels output munalsingh/codedoctor-cpu-bench -p build/kernel_cpubench/out
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from app.packaging import build_payload  # noqa: E402

KERNEL_ID = "munalsingh/codedoctor-cpu-bench"
#: the versions this repo runs locally, so the recipe is the same
PINS = "'transformers==4.57.6' 'sentence-transformers==5.0.0'"

KERNEL = r'''"""CodeDoctor: CPU-only query-encoding benchmark (generated by
scripts/build_cpubench_kernel.py; do not edit)."""
import base64, io, os, subprocess, sys, tarfile
os.environ["CUDA_VISIBLE_DEVICES"] = ""
subprocess.run(f"{sys.executable} -m pip install -q __PINS__ psutil", shell=True, check=True)
WORK = "/kaggle/working/codedoctor"
os.makedirs(WORK, exist_ok=True)
with tarfile.open(fileobj=io.BytesIO(base64.b64decode("__PAYLOAD__")), mode="r:gz") as tar:
    tar.extractall(WORK)
subprocess.run([sys.executable, "scripts/bench_query_cpu.py", "--subset", "build/kernel_cpubench/subset",
                "--out", "/kaggle/working/cpu_latency.json"], cwd=WORK, check=False)
print(open("/kaggle/working/cpu_latency.json").read() if os.path.exists("/kaggle/working/cpu_latency.json") else "NO RESULT")
'''


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "build" / "kernel_cpubench")
    args = parser.parse_args(argv)
    subset = args.out / "subset"
    if not (subset / "subset.json").exists():
        print(f"missing {subset}; run bench_query_cpu.py --build-subset first")
        return 1
    # only what the benchmark imports: the encoder, its config, and the subset
    paths = ("app/__init__.py", "app/retrieval/__init__.py", "app/retrieval/encode.py",
             "config/frozen.yaml", "config/retrieval.yaml", "scripts/__init__.py",
             "scripts/bench_query_cpu.py", "build/kernel_cpubench/subset")
    payload, included = build_payload(paths)
    script = KERNEL.replace("__PAYLOAD__", payload).replace("__PINS__", PINS)
    (args.out / "codedoctor-cpu-bench.py").write_text(script, encoding="utf-8")
    (args.out / "kernel-metadata.json").write_text(json.dumps({
        "id": KERNEL_ID, "title": "codedoctor-cpu-bench", "code_file": "codedoctor-cpu-bench.py",
        "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": False,
        "enable_tpu": False, "enable_internet": True, "dataset_sources": [],
        "kernel_sources": [], "competition_sources": [], "model_sources": [],
    }, indent=2), encoding="utf-8")
    print(f"kernel -> {args.out} ({len(script) / 1e6:.1f} MB); included {len(included)} paths")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
