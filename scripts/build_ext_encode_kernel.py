"""Build a Kaggle GPU kernel that encodes the external sets with F2LLM-v2-1.7B.

The 1.7B APPS vectors come from the kernel ``munalsingh/codedoctor-apps-encode``.
The external sets (CodeContests EXT, the versions benchmark) reuse those vectors
for every text already in the APPS corpus and need only their new texts
encoded.  This kernel encodes exactly those, with the same recipe and code
path as that kernel, plus a drift probe: APPS texts whose 1.7B vectors we
already hold, so a changed library or GPU shows up as cosine < 1.

    python scripts/build_ext_encode_kernel.py --out build/kernel_ext17b
    kaggle kernels push -p build/kernel_ext17b
    kaggle kernels output munalsingh/codedoctor-ext-encode-17b -p build/kernel_ext17b/out
    python scripts/build_ext_encode_kernel.py --assemble build/kernel_ext17b/out

Offline pre-processing: the FAQ allows a GPU here.
"""

from __future__ import annotations

import argparse
import base64
import gzip
import json
import random
import sys
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from scripts.dev_eval import load_jsonl_texts  # noqa: E402

TAG = "f2llm17b"
MODEL = "codefuse-ai/F2LLM-v2-1.7B"
REVISION = "3766d46e7a68545ed6190c15330983f9b39ab718"
KERNEL_ID = "munalsingh/codedoctor-ext-encode-17b"
SETS = ("ext_cc", "versions_apps")
PROBE_DOCS, PROBE_QUERIES = 64, 32

KERNEL = r'''"""CodeDoctor: encode external-set texts with F2LLM-v2-1.7B (generated by
scripts/build_ext_encode_kernel.py; do not edit).  Recipe copied from
munalsingh/codedoctor-apps-encode."""
import base64, gzip, json, subprocess, sys, time
t_start = time.time()
import os
os.environ.setdefault("PYTORCH_ALLOC_CONF", "expandable_segments:True")
def log(*a): print(f"[{time.time() - t_start:8.1f}s]", *a, flush=True)
subprocess.run(f"{sys.executable} -m pip install -q -U 'sentence-transformers>=5.0' 'transformers>=4.57'",
               shell=True, check=True)
import numpy as np, torch, transformers, sentence_transformers
from sentence_transformers import SentenceTransformer
DTYPE = (torch.bfloat16 if torch.cuda.get_device_capability(0)[0] >= 8 else torch.float16) \
    if torch.cuda.is_available() else torch.float32
versions = {"torch": torch.__version__, "transformers": transformers.__version__,
            "sentence_transformers": sentence_transformers.__version__, "dtype": str(DTYPE),
            "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else None}
log(versions)
OUT = "/kaggle/working"
INSTRUCTION = "Instruct: Retrieve the most relevant code snippet for the given query.\nQuery: "
MAX_SEQ_LENGTH = 8192
ATTENTION_BUDGET = 67_000_000
MAX_BATCH = 64
PAYLOAD = json.loads(gzip.decompress(base64.b64decode("__PAYLOAD__")))

def encode_length_aware(model, texts, prompt):
    tokenizer = model.tokenizer
    prompt_len = len(tokenizer.encode(prompt, add_special_tokens=False)) if prompt else 0
    lengths = [min(MAX_SEQ_LENGTH, prompt_len + len(tokenizer.encode(t, add_special_tokens=False)) + 1)
               for t in texts]
    order = sorted(range(len(texts)), key=lambda i: lengths[i])
    batches, current, current_max = [], [], 0
    for i in order:
        candidate_max = max(current_max, lengths[i])
        cost = candidate_max * candidate_max * (len(current) + 1)
        if current and (cost > ATTENTION_BUDGET or len(current) >= MAX_BATCH):
            batches.append(current); current, current_max = [i], lengths[i]
        else:
            current.append(i); current_max = candidate_max
    if current:
        batches.append(current)
    out = [None] * len(texts)
    for batch in batches:
        emb = model.encode([texts[i] for i in batch], prompt=prompt, batch_size=len(batch),
                           show_progress_bar=False, convert_to_numpy=True, normalize_embeddings=True)
        for slot, vector in zip(batch, emb):
            out[slot] = vector
    return np.asarray(np.vstack(out), dtype=np.float32)

model = SentenceTransformer(
    "__MODEL__", revision="__REVISION__",
    device="cuda" if torch.cuda.is_available() else "cpu",
    tokenizer_kwargs={"add_eos_token": True, "model_max_length": MAX_SEQ_LENGTH},
    model_kwargs={"torch_dtype": DTYPE, "attn_implementation": "sdpa"},
)
model.max_seq_length = MAX_SEQ_LENGTH
model.eval()
log("loaded; pooling", model[1].get_config_dict())
seconds = {}
for name, texts in PAYLOAD["queries"].items():
    t0 = time.time()
    np.save(f"{OUT}/q_{name}.npy", encode_length_aware(model, texts, INSTRUCTION).astype(np.float16))
    seconds["q_" + name] = time.time() - t0; log("queries", name, len(texts))
for name, texts in PAYLOAD["documents"].items():
    t0 = time.time()
    np.save(f"{OUT}/d_{name}.npy", encode_length_aware(model, texts, None).astype(np.float16))
    seconds["d_" + name] = time.time() - t0; log("documents", name, len(texts))
json.dump({"versions": versions, "seconds": seconds, "model": "__MODEL__", "revision": "__REVISION__"},
          open(f"{OUT}/run.json", "w"), indent=1)
log("DONE")
'''


def _new_texts(folder: Path, apps_corpus: set[str]) -> tuple[list[str], list[str]]:
    _, queries = load_jsonl_texts(folder / "texts_queries.jsonl")
    _, corpus = load_jsonl_texts(folder / "texts_corpus.jsonl")
    new_docs = sorted({t for t in corpus if t not in apps_corpus})
    return queries, new_docs


def build(out: Path, artifacts: Path) -> int:
    _, apps_corpus = load_jsonl_texts(artifacts / "apps" / "texts_corpus.jsonl")
    _, apps_queries = load_jsonl_texts(artifacts / "apps" / "texts_queries_train.jsonl")
    apps_set = set(apps_corpus)
    payload = {"queries": {}, "documents": {}}
    for name in SETS:
        queries, docs = _new_texts(artifacts / name, apps_set)
        payload["queries"][name] = queries
        payload["documents"][name] = docs
    rng = random.Random(20260924)
    probe_docs = sorted(rng.sample(range(len(apps_corpus)), PROBE_DOCS))
    probe_queries = sorted(rng.sample(range(len(apps_queries)), PROBE_QUERIES))
    payload["documents"]["probe_apps"] = [apps_corpus[i] for i in probe_docs]
    payload["queries"]["probe_apps"] = [apps_queries[i] for i in probe_queries]
    blob = base64.b64encode(gzip.compress(json.dumps(payload).encode("utf-8"), 9)).decode("ascii")
    out.mkdir(parents=True, exist_ok=True)
    script = KERNEL.replace("__PAYLOAD__", blob).replace("__MODEL__", MODEL).replace("__REVISION__", REVISION)
    (out / "codedoctor-ext-encode-17b.py").write_text(script, encoding="utf-8")
    (out / "kernel-metadata.json").write_text(json.dumps({
        "id": KERNEL_ID, "title": "codedoctor-ext-encode-17b", "code_file": "codedoctor-ext-encode-17b.py",
        "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
        "enable_tpu": False, "enable_internet": True, "keywords": ["gpu"], "dataset_sources": [],
        "kernel_sources": [], "competition_sources": [], "model_sources": [],
    }, indent=2), encoding="utf-8")
    (out / "probe.json").write_text(json.dumps({"docs": probe_docs, "queries": probe_queries}), encoding="utf-8")
    counts = {k: {n: len(v) for n, v in d.items()} for k, d in payload.items()}
    print(f"kernel -> {out}  ({len(script) / 1e6:.1f} MB script)  {counts}")
    return 0


def assemble(kernel_out: Path, artifacts: Path, probe_file: Path) -> int:
    _, apps_corpus = load_jsonl_texts(artifacts / "apps" / "texts_corpus.jsonl")
    apps_vec = np.load(artifacts / "apps" / f"emb_{TAG}_corpus.npy").astype(np.float32)
    qtrain_vec = np.load(artifacts / "apps" / f"emb_{TAG}_qtrain.npy").astype(np.float32)
    by_text = {t: i for i, t in enumerate(apps_corpus)}

    probe = json.loads(probe_file.read_text(encoding="utf-8"))
    report = {}
    for kind, stored, key in (("docs", apps_vec, "d_probe_apps"), ("queries", qtrain_vec, "q_probe_apps")):
        new = np.load(kernel_out / f"{key}.npy").astype(np.float32)
        old = stored[probe[kind]]
        cos = (new * old).sum(1) / np.linalg.norm(new, axis=1) / np.linalg.norm(old, axis=1)
        report[kind] = {"min": round(float(cos.min()), 5), "median": round(float(np.median(cos)), 5)}
    print("drift probe (new run vs the vectors in artifacts/apps):", report)
    if min(r["min"] for r in report.values()) < 0.99:
        print("REFUSING to assemble: the new run does not reproduce the stored 1.7B vectors (min cosine < 0.99).")
        return 1

    for name in SETS:
        folder = artifacts / name
        queries, new_docs = _new_texts(folder, set(apps_corpus))
        q = np.load(kernel_out / f"q_{name}.npy")
        d = np.load(kernel_out / f"d_{name}.npy").astype(np.float32)
        assert len(q) == len(queries) and len(d) == len(new_docs), name
        new_index = {t: i for i, t in enumerate(new_docs)}
        _, corpus = load_jsonl_texts(folder / "texts_corpus.jsonl")
        rows = [apps_vec[by_text[t]] if t in by_text else d[new_index[t]] for t in corpus]
        np.save(folder / f"emb_{TAG}_queries.npy", q)
        np.save(folder / f"emb_{TAG}_corpus.npy", np.asarray(rows, dtype=np.float16))
        print(f"{name}: queries {q.shape}, corpus {len(rows)} ({len(new_docs)} new, {len(rows) - len(new_docs)} reused)")
    run = json.loads((kernel_out / "run.json").read_text(encoding="utf-8"))
    (artifacts / "ext_cc" / f"encode_{TAG}.json").write_text(
        json.dumps({"kernel": KERNEL_ID, "run": run, "drift_probe": report}, indent=1), encoding="utf-8")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "build" / "kernel_ext17b")
    parser.add_argument("--artifacts", type=Path, default=REPO_ROOT / "artifacts")
    parser.add_argument("--assemble", type=Path, default=None, help="downloaded kernel output folder")
    args = parser.parse_args(argv)
    if args.assemble is not None:
        return assemble(args.assemble, args.artifacts, args.out / "probe.json")
    return build(args.out, args.artifacts)


if __name__ == "__main__":
    raise SystemExit(main())
