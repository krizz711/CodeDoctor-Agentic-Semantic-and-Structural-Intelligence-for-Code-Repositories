"""Package the pipeline into a self-contained Kaggle evaluation kernel.

The screening run needs a GPU for the accuracy tier, and Kaggle offers one.
Rather than publishing the repo to get it there, this embeds the modules the
evaluation actually imports as a base64 tarball inside the generated script,
so the kernel is reproducible from this repo and depends on nothing external
except the public model and dataset.

    python scripts/build_eval_kernel.py --out build/kernel
    kaggle kernels push -p build/kernel

The generated script runs ``mteb.evaluate`` with the real
``PrePostPipelineEncoder`` — the emitted JSON is MTEB's own, never assembled
by hand.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from app.packaging import build_payload  # noqa: E402

KERNEL_TEMPLATE = '''"""CodeDoctor — MTEB AppsRetrieval submission run (generated; do not edit).

Generated by scripts/build_eval_kernel.py from the CodeDoctor repository.
The pipeline source is embedded below as a base64 tarball so this kernel is
reproducible without publishing the repository.
"""

import base64
import io
import json
import os
import subprocess
import sys
import tarfile
import time

t_start = time.time()
os.environ.setdefault("PYTORCH_ALLOC_CONF", "expandable_segments:True")


def log(*a):
    print(f"[{{time.time() - t_start:8.1f}}s]", *a, flush=True)


PAYLOAD = "{payload}"

WORK = "/kaggle/working/codedoctor"
os.makedirs(WORK, exist_ok=True)
with tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD)), mode="r:gz") as tar:
    tar.extractall(WORK)
sys.path.insert(0, WORK)
log("unpacked pipeline into", WORK)

subprocess.run(
    f"{{sys.executable}} -m pip install -q -U 'mteb==2.21.0' 'sentence-transformers>=5.0' "
    f"'transformers>=4.57' datasets pyyaml",
    shell=True,
    check=True,
)

import numpy as np
import torch

# Turing (T4) has no native bfloat16; torch emulates it and the run crawls.
if torch.cuda.is_available():
    DTYPE = "bfloat16" if torch.cuda.get_device_capability(0)[0] >= 8 else "float16"
    log("gpu", torch.cuda.get_device_name(0), "dtype", DTYPE)
else:
    DTYPE = "float32"
    log("no gpu; running on cpu with", DTYPE)

os.chdir(WORK)
from app.pipeline.encoder import PrePostPipelineEncoder
from app.pipeline.execution_rerank import ExecutionConfig
from app.pipeline.reranker import RerankerConfig
from app.retrieval.encode import CodeEncoder
from scripts.evaluate_mteb import build_mteb_encoder, get_pipeline_config, get_tier_model

import mteb

TIER = "{tier}"
RERANK = {rerank}
EXECUTION = {execution}
EXECUTION_CANDIDATES = {execution_candidates}
OUT = "/kaggle/working"

model_name, revision = get_tier_model(TIER)
log("tier", TIER, "model", model_name, revision)

encoder = CodeEncoder(
    model_name=model_name,
    revision=revision,
    device="cuda" if torch.cuda.is_available() else "cpu",
    tier=TIER,
    torch_dtype=DTYPE,
)
log("query prefix   :", repr(encoder.query_prefix))
log("document prefix:", repr(encoder.document_prefix))
log("max_seq_length :", encoder.max_seq_length, "add_eos_token:", encoder.add_eos_token)

config = RerankerConfig() if not RERANK else RerankerConfig.load()
log("reranker:", config.describe())

# Read the comparison rule from the frozen config rather than hardcoding it
# here, so this kernel and a local `python scripts/evaluate_mteb.py` cannot
# disagree about how a candidate's output is judged.
_pipeline_defaults = get_pipeline_config()
execution_config = ExecutionConfig(
    enabled=EXECUTION,
    max_candidates=EXECUTION_CANDIDATES,
    numeric_tolerance=_pipeline_defaults["execution_numeric_tolerance"],
)
log("execution pass:", "ENABLED top-%d" % EXECUTION_CANDIDATES if EXECUTION else "off")
log("numeric tolerance:", execution_config.numeric_tolerance)

pipeline = PrePostPipelineEncoder(encoder, config, execution_config=execution_config)
hub_path = __import__("pathlib").Path(WORK) / "artifacts" / "hubness.npz"
if hub_path.exists():
    # Aligned onto MTEB's corpus by document content, not by row index.
    pipeline.hub_profile_path = hub_path
    log("hub profile attached:", hub_path)

mteb_model = build_mteb_encoder(pipeline, model_name)
task = mteb.get_task("AppsRetrieval")
log("evaluating ...")
results = mteb.evaluate(
    mteb_model, [task], encode_kwargs={{"batch_size": 64}},
    prediction_folder=os.path.join(OUT, "predictions"),
)
task_result = list(results.task_results)[0]
payload = task_result.to_dict()

suffix = "" if (RERANK or EXECUTION) else "_dense_only"
out_json = os.path.join(OUT, f"appsretrieval_results{{suffix}}.json")
with open(out_json, "w") as handle:
    json.dump(payload, handle, default=str, indent=2)

scores = payload.get("scores", {{}}).get("test", [{{}}])[0]
if pipeline.execution_audit:
    log("execution audit:", pipeline.execution_audit)
    with open(os.path.join(OUT, "execution_audit.json"), "w") as handle:
        json.dump(pipeline.execution_audit, handle, indent=2)
log("*** NDCG@10 =", scores.get("ndcg_at_10"), " MRR@10 =", scores.get("mrr_at_10"), "***")
log("wrote", out_json)

try:
    from scripts.export_submission_csv import export_from_predictions

    for path in export_from_predictions(
        __import__("pathlib").Path(os.path.join(OUT, "predictions")), payload,
        __import__("pathlib").Path(OUT),
    ):
        log("wrote", path)
except Exception as exc:
    log("csv export skipped:", type(exc).__name__, exc)

log("DONE")
'''

METADATA_TEMPLATE = {
    "id": "munalsingh/{slug}",
    "title": "{slug}",
    "code_file": "run.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": True,
    "enable_gpu": True,
    "enable_internet": True,
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "build" / "kernel")
    parser.add_argument("--slug", default="codedoctor-apps-eval")
    parser.add_argument("--tier", choices=["accuracy", "interactive"], default="accuracy")
    parser.add_argument("--no-rerank", action="store_true", help="generate the dense-only ablation run")
    parser.add_argument("--execution", action="store_true", help="enable the execution pass in the kernel")
    parser.add_argument("--execution-candidates", type=int, default=10)
    parser.add_argument("--hubness", type=Path, default=None, help="hub profile .npz to embed")
    args = parser.parse_args()

    print("Packing pipeline ...")
    extra: tuple[str, ...] = ()
    if args.hubness and args.hubness.exists():
        staged = REPO_ROOT / "artifacts" / "hubness.npz"
        staged.parent.mkdir(parents=True, exist_ok=True)
        staged.write_bytes(args.hubness.read_bytes())
        extra = ("artifacts/hubness.npz",)
    payload, included = build_payload(extra=extra)
    print(f"  packed {len(included)} paths -> {len(payload) / 1024:.0f} KB base64")

    args.out.mkdir(parents=True, exist_ok=True)
    script = KERNEL_TEMPLATE.format(
        payload=payload,
        tier=args.tier,
        rerank="False" if args.no_rerank else "True",
        execution="True" if args.execution else "False",
        execution_candidates=args.execution_candidates,
    )
    (args.out / "run.py").write_text(script, encoding="utf-8")

    metadata = {k: v.format(slug=args.slug) if isinstance(v, str) else v
                for k, v in METADATA_TEMPLATE.items()}
    (args.out / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    print(f"Wrote {args.out / 'run.py'} and {args.out / 'kernel-metadata.json'}")
    print(f"Next: kaggle kernels push -p {args.out}")
    if extra:
        print(f"      (embedded hub profile from {args.hubness})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
